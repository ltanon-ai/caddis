//! sha256.rs — std-only SHA-256 for the remember write path.
//!
//! The crate law is ZERO runtime deps (sovereignty, canon D-023 family):
//! I1's byte-exact audit anchor needs a hash, so the hash is ours. FIPS
//! 180-4, checked against the standard vectors in tests. This is NOT on
//! the recall hot path — remember() writes are rare and audited.

